export const QUESTIONS: Question[] = Object.entries(BANK).flatMap(([ch, list]) =>
  list.map(([text, answer, explanation], i) => ({
    id: `c${ch.padStart(2, '0')}-${String(i + 1).padStart(3, '0')}`,
    chapter: Number(ch),
    text,
    answer,
    explanation,
  })),
);

const byId = new Map(QUESTIONS.map((q) => [q.id, q]));
export const questionById = (id: string) => byId.get(id);
export const questionsOfChapter = (chapter: number) => QUESTIONS.filter((q) => q.chapter === chapter);
