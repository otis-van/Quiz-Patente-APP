export type IconName = keyof typeof ICONS;

const colorOf = (ch: string, C: Palette): string | null => {
  switch (ch) {
    case 'k': return C.ink;
    case 't': return C.text;
    case 'w': return '#FFFFFF';
    case 'c': return '#FFF3DC';
    case 'y': return C.yellow;
    case 'o': return C.orange;
    case 'r': return C.red;
    case 'p': return C.pink;
    case 'l': return C.lilac;
    case 'b': return C.blue;
    case 'm': return C.mint;
    case 'g': return C.green;
    case 's': return '#CFC8BC';
    case 'd': return '#5E5E66';
    default: return null;
  }
};

/** Rettangoli per riga (pixel adiacenti dello stesso colore uniti in uno solo). */
function runs(rows: readonly string[]) {
  const out: { x: number; y: number; w: number; ch: string }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      let w = 1;
      while (row[x + w] === ch) w++;
      if (ch !== '.') out.push({ x, y, w, ch });
      x += w;
    }
  });
  return out;
}

const RUNS = Object.fromEntries(Object.entries(ICONS).map(([k, v]) => [k, runs(v)])) as Record<
  IconName,
  ReturnType<typeof runs>
>;

interface Props {
  name: IconName;
  size?: number;
  /** Specchia orizzontalmente (es. freccia "avanti"). */
  flip?: boolean;
  /** Versione spenta (es. lucchetto, elementi bloccati). */
  dim?: boolean;
}

export const PixelIcon = memo(function PixelIcon({ name, size = 24, flip, dim }: Props) {
  const C = useColors();
  return (
    <Svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      style={[flip && { transform: [{ scaleX: -1 }] }, dim && { opacity: 0.45 }]}>
      {RUNS[name].map((r, i) => {
        const fill = colorOf(r.ch, C);
        return fill ? <Rect key={i} x={r.x} y={r.y} width={r.w + 0.02} height={1.04} fill={fill} /> : null;
      })}
    </Svg>
  );
});
